#!/usr/bin/env bash
# Generate addon/Secrets.js from the current tunnel URL + API key, then push the add-on.
# Secrets.js is gitignored; it only ever goes to the private Apps Script project.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export PATH="$ROOT/.tools/bin:$HOME/.local/bin:$PATH"   # .tools: installed by scripts/install-tools.sh
mkdir -p "$ROOT/.run"
URL="${1:-$(cat "$ROOT/.run/url")}"
KEY="$(grep '^MAILLENS_API_KEY=' "$ROOT/backend/.env" | cut -d= -f2-)"
# MAILLENS_BUILD=prod produces the user-facing build: no developer tools anywhere in the UI.
DEV=$([ "${MAILLENS_BUILD:-dev}" = "prod" ] && echo False || echo True)
# Inbox scan web app: an owner-only versioned deployment (/exec), kept at the same id across pushes and
# updated to the new code below. Google can show /exec pages inside the dashboard's frame; the /dev test
# URL is the fallback until that deployment exists.
SCAN_ID_FILE="$ROOT/.run/scan-deployment-id"
SCAN_ID="$(cat "$SCAN_ID_FILE" 2>/dev/null || true)"
if [ -n "$SCAN_ID" ]; then SCAN_URL="https://script.google.com/macros/s/$SCAN_ID/exec"; else
  # No Apps Script project yet (run scripts/setup-addon.sh first) must not abort the script silently.
  HEAD_ID="$(cd "$ROOT" && { clasp deployments 2>/dev/null || true; } | awk '/@HEAD/ {print $2}' | head -1)"
  SCAN_URL=""; [ -n "$HEAD_ID" ] && SCAN_URL="https://script.google.com/macros/s/$HEAD_ID/dev"
fi
echo "scan web app: ${SCAN_URL:-not available (no deployment found)}"
(umask 077; URL="$URL" KEY="$KEY" DEV="$DEV" SCAN_URL="$SCAN_URL" python3 - > "$ROOT/addon/Secrets.js" <<'PY'
import json, os
print("// GENERATED by scripts/push-addon.sh. Gitignored. Do not commit.")
print("var DEV_DEFAULTS = " + json.dumps({"url": os.environ["URL"], "apiKey": os.environ["KEY"],
                                          "dev": os.environ["DEV"] == "True", "scanUrl": os.environ["SCAN_URL"] or None}) + ";")
PY
)
echo "build: ${MAILLENS_BUILD:-dev}"
# F-09: allow outbound fetches ONLY to this exact backend origin and the Gmail API. The committed
# manifest lists just the Gmail API; the backend origin is injected for this push, then restored.
cp "$ROOT/addon/appsscript.json" "$ROOT/.run/appsscript.committed.json"
trap 'cp "$ROOT/.run/appsscript.committed.json" "$ROOT/addon/appsscript.json"' EXIT
URL="$URL" python3 - "$ROOT/addon/appsscript.json" <<'PY'
import json, os, sys
from urllib.parse import urlsplit
u = urlsplit(os.environ["URL"])
assert u.scheme == "https" and u.hostname and not u.path.strip("/"), "backend URL must be an https origin"
m = json.load(open(sys.argv[1]))
m["urlFetchWhitelist"] = ["https://gmail.googleapis.com/", f"https://{u.hostname}/"]  # top-level manifest field
# OpenLink must be HTTPS and allow-listed: only this deployment's dashboard path (Security Console).
m["addOns"]["common"]["openLinkUrlPrefixes"] = [f"https://{u.hostname}/dashboard/"]
json.dump(m, open(sys.argv[1], "w"), indent=2)
print("allow-list:", m["urlFetchWhitelist"], "| open-link:", m["addOns"]["common"]["openLinkUrlPrefixes"])
PY
if [ "${DRY_RUN:-0}" = "1" ]; then
  echo "DRY_RUN: generated addon/Secrets.js and the manifest allow-list above; nothing pushed."
  cp "$ROOT/addon/appsscript.json" "$ROOT/.run/appsscript.dryrun.json"
  exit 0
fi
[ -f "$ROOT/.clasp.json" ] || { echo "No Apps Script project yet: run scripts/setup-addon.sh <your tunnel URL> first."; exit 1; }
cd "$ROOT" && clasp push --force | tee "$ROOT/.run/push.log"
grep -q "Pushed" "$ROOT/.run/push.log" || { echo "PUSH FAILED"; exit 1; }
# Keep the scan web-app deployment on the code just pushed (create it once, then update in place).
if [ "${DRY_RUN:-0}" != "1" ]; then
  if [ -n "$SCAN_ID" ]; then
    (cd "$ROOT" && clasp update-deployment "$SCAN_ID" --description "MailLens inbox scan" >/dev/null) && echo "scan web app updated (/exec)"
  else
    NEW_ID="$(cd "$ROOT" && clasp create-deployment --description "MailLens inbox scan" 2>&1 | grep -oE 'AKfy[A-Za-z0-9_-]+' | head -1)"
    if [ -n "$NEW_ID" ]; then
      echo "$NEW_ID" > "$SCAN_ID_FILE"
      echo "scan web app deployed (/exec); pushing again so the add-on uses it"
      cp "$ROOT/.run/appsscript.committed.json" "$ROOT/addon/appsscript.json"  # exec skips the EXIT trap
      exec "$0" "$@"
    else
      echo "WARNING: could not create the scan web-app deployment; the /dev test URL stays in use"
    fi
  fi
fi
